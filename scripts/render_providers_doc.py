"""Render docs/PROVIDERS.md from bifrost/config.json + disabled-providers.json.

The provider list in prose docs drifted three times (CLAUDE.md, README.md and
ADA's 50-llm.md all named parked providers as active on 2026-09-25). This
file is GENERATED; the gate fails if it is stale (`--check`). Model names and
key COUNTS only -- never key values.

    python scripts/render_providers_doc.py          # rewrite docs/PROVIDERS.md
    python scripts/render_providers_doc.py --check  # exit 1 if out of date
"""

