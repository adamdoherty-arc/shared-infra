def _models(block: dict) -> list[str]:
    seen: list[str] = []
    for key in block.get("keys", []):
        for m in key.get("models", []):
            if m not in seen:
                seen.append(m)
    return seen


def _aliases(block: dict) -> dict[str, str]:
    out: dict[str, str] = {}
    for key in block.get("keys", []):
        out.update(key.get("aliases") or {})
    return out


def render() -> str:
    cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    dis = json.loads(DISABLED.read_text(encoding="utf-8"))
    active = cfg.get("providers", {})
    parked = {k: v for k, v in dis.get("providers", dis).items() if isinstance(v, dict) and k not in active}
    lines = [
        "# Bifrost providers",
        "",
        "GENERATED by `scripts/render_providers_doc.py` from `bifrost/config.json` and",
        "`bifrost/disabled-providers.json`. Do not hand-edit; the gate (`scripts/gate.py`)",
        "fails when this file is stale. Call a model as `<provider>/<model>` with a",
        "virtual key (`x-bf-vk` or `Authorization: Bearer`).",
        "",
        f"## Active ({len(active)})",
        "",
        "| Provider | Tier | Keys | Models | Limits |",
        "|---|---|---|---|---|",
    ]
    for name, block in active.items():
        tier, limits = META.get(name, ("?", "not recorded -- add to META"))
        aliases = _aliases(block)
        real = [m for m in _models(block) if m not in aliases]
        lines.append(
            f"| `{name}` | {tier} | {len(block.get('keys', []))} | {len(real)} (+{len(aliases)} aliases) | {limits} |"
        )
    lines += ["", "### Models per active provider", ""]
    for name, block in active.items():
        aliases = _aliases(block)
        real = [m for m in _models(block) if m not in aliases]
        lines.append(f"- **{name}**: " + ", ".join(f"`{m}`" for m in real))
        if aliases:
            lines.append("  - aliases: " + ", ".join(f"`{a}` -> `{t}`" for a, t in aliases.items()))
    lines += [
        "",
        f"## Parked ({len(parked)})",
        "",
        "| Provider | Tier | Why parked / how to restore |",
        "|---|---|---|",
    ]
    for name, block in parked.items():
        tier, limits = META.get(name, ("?", ""))
        why = " ".join(str(block.get("_comment", "")).split())
        why = (why[:220] + "...") if len(why) > 220 else why
        lines.append(f"| `{name}` | {tier} | {why or limits} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/PROVIDERS.md is stale: run python scripts/render_providers_doc.py")
            return 1
        print("docs/PROVIDERS.md up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
